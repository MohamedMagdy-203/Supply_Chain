"""Full model comparison report (all models, all metrics, breakdowns).

Complements src/evaluate.py (which stays the strict pinball check). This module
reads every predictions/*.parquet and writes:

    reports/model_comparison.md        the report (tables + selection section)
    reports/model_metrics.csv          one row per model and split
    reports/model_breakdown_test.csv   test results by department, store, demand type

Run from the repository root:
    python -m src.evaluate_report
    python -m src.evaluate_report --models naive ma4 linear quantreg lgbm deep

Rules (same as evaluate.py)
  * Validation is used to compare and select. Test is reporting only.
  * Every model must contain exactly the validation + test keys of features.parquet.
  * All models are scored by the same code on the same rows.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from src.config import KEY_COLS, PREDICTIONS_DIR, QUANTILE_COLS, QUANTILE_LEVELS
from src.data import load_features, load_series_type

BASELINES = ("naive", "ma4")
EXCLUDE = {"fake"}                      # development data for the API, never a model
MARKER = "<!-- generated by src.evaluate_report -->"
LEVELS = np.array(list(QUANTILE_LEVELS.values()))


# ---------------------------------------------------------------- loading
def discover_models(predictions_dir: Path) -> list[str]:
    return sorted(p.stem for p in Path(predictions_dir).glob("*.parquet") if p.stem not in EXCLUDE)


def load_predictions(path: Path) -> pd.DataFrame:
    df = pd.read_parquet(path)
    required = KEY_COLS + QUANTILE_COLS
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"{path.name}: missing columns {missing}")
    df = df[required].copy()
    if df.duplicated(KEY_COLS).any():
        raise ValueError(f"{path.name}: duplicate forecast keys")
    values = df[QUANTILE_COLS].to_numpy(float)
    if not np.isfinite(values).all():
        raise ValueError(f"{path.name}: NaN or infinite quantiles")
    if (np.diff(values, axis=1) < -1e-10).any():
        raise ValueError(f"{path.name}: crossing quantiles")
    if (values < 0).any():
        raise ValueError(f"{path.name}: negative quantiles")
    return df


def check_coverage(pred: pd.DataFrame, truth_all: pd.DataFrame, name: str) -> None:
    """The file must hold exactly the validation + test keys, nothing more or less."""
    expected = set(map(tuple, truth_all[KEY_COLS].itertuples(index=False, name=None)))
    actual = set(map(tuple, pred[KEY_COLS].itertuples(index=False, name=None)))
    if expected != actual:
        raise ValueError(f"{name}: keys do not match validation + test rows "
                         f"(missing={len(expected - actual)}, unexpected={len(actual - expected)})")


# ---------------------------------------------------------------- metrics
def compute_metrics(y: np.ndarray, Q: np.ndarray) -> dict:
    """y: (n,) actual demand. Q: (n, 7) quantile forecasts in QUANTILE_COLS order."""
    err = y[:, None] - Q
    pinball = np.maximum(LEVELS * err, (LEVELS - 1.0) * err).mean(axis=0)

    out = {"mean_pinball": float(pinball.mean())}
    for c, v in zip(QUANTILE_COLS, pinball):
        out[f"pinball_{c}"] = float(v)
    for j, c in enumerate(QUANTILE_COLS):
        out[f"sl_{c}"] = float((y <= Q[:, j]).mean())          # share of weeks demand <= forecast

    q10, q25, q50, q75, q90 = (Q[:, j] for j in range(5))
    out["cov80"] = float(((y >= q10) & (y <= q90)).mean())
    out["cov50"] = float(((y >= q25) & (y <= q75)).mean())
    out["width80"] = float((q90 - q10).mean())
    out["width50"] = float((q75 - q25).mean())

    resid = y - q50                                              # q50 is the point forecast
    out["mae"] = float(np.abs(resid).mean())
    out["rmse"] = float(np.sqrt((resid ** 2).mean()))
    out["r2"] = float(1 - (resid ** 2).sum() / ((y - y.mean()) ** 2).sum())
    out["wape"] = float(np.abs(resid).sum() / y.sum())
    pos = y > 0                                                  # MAPE only where demand > 0
    out["mape_pos"] = float((np.abs(resid[pos]) / y[pos]).mean())
    return out


def _group_table(df: pd.DataFrame, models: list[str], by: str) -> pd.DataFrame:
    """Mean pinball and WAPE per group (rows) and model (columns). df has y_next and per-model quantiles."""
    rows = []
    for g, idx in df.groupby(by).groups.items():
        sub = df.loc[idx]
        y = sub["y_next"].to_numpy(float)
        row = {"group": g, "n": len(sub)}
        for m in models:
            met = compute_metrics(y, sub[[f"{m}__{c}" for c in QUANTILE_COLS]].to_numpy(float))
            row[f"{m} pinball"] = met["mean_pinball"]
            row[f"{m} wape"] = met["wape"]
        rows.append(row)
    return pd.DataFrame(rows).set_index("group")


# ---------------------------------------------------------------- markdown helpers
def _fmt(v, nd=3) -> str:
    if isinstance(v, (float, np.floating)):
        return f"{v:.{nd}f}"
    return str(v)


def _md(df: pd.DataFrame, index_name: str = "model", nd: int = 3) -> str:
    d = df.reset_index()
    d.columns = [index_name] + list(d.columns[1:])
    cols = [str(c) for c in d.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in d.iterrows():
        lines.append("| " + " | ".join(_fmt(v, nd) for v in r) + " |")
    return "\n".join(lines)


# ---------------------------------------------------------------- main
def run(features: pd.DataFrame | None = None, series_type: pd.DataFrame | None = None,
        predictions_dir: Path = PREDICTIONS_DIR, out: Path = Path("reports/model_comparison.md"),
        models: list[str] | None = None, force: bool = False) -> Path:
    out = Path(out)
    if out.exists() and not force and MARKER not in out.read_text(encoding="utf-8", errors="ignore")[:300]:
        raise FileExistsError(
            f"{out} was not written by this script (another member's report?). "
            f"Rename it first (git mv), or pass --force to overwrite.")

    feats = features if features is not None else load_features()
    st = series_type if series_type is not None else load_series_type()
    val = feats[feats["split"] == "val"].reset_index(drop=True)
    test = feats[feats["split"] == "test"].reset_index(drop=True)
    truth_all = pd.concat([val, test], ignore_index=True)

    models = models or discover_models(predictions_dir)
    if not models:
        raise FileNotFoundError(f"No prediction files in {predictions_dir}")
    preds = {}
    for m in models:
        p = load_predictions(Path(predictions_dir) / f"{m}.parquet")
        check_coverage(p, truth_all, m)
        preds[m] = p

    def attach(truth: pd.DataFrame) -> pd.DataFrame:
        df = truth[KEY_COLS + ["y_next", "dept_id", "store_id"]].merge(
            st[["series_id", "demand_type"]], on="series_id", how="left")
        for m, p in preds.items():
            renamed = p.rename(columns={c: f"{m}__{c}" for c in QUANTILE_COLS})
            df = df.merge(renamed, on=KEY_COLS, how="left", validate="one_to_one")
        return df

    scored = {"val": attach(val), "test": attach(test)}
    rows = []
    for split, df in scored.items():
        y = df["y_next"].to_numpy(float)
        for m in models:
            met = compute_metrics(y, df[[f"{m}__{c}" for c in QUANTILE_COLS]].to_numpy(float))
            rows.append({"model": m, "split": split, "n": len(df), **met})
    metrics = pd.DataFrame(rows)

    out.parent.mkdir(parents=True, exist_ok=True)
    metrics.to_csv(out.parent / "model_metrics.csv", index=False)

    breakdown = {by: _group_table(scored["test"], models, by) for by in ["dept_id", "store_id", "demand_type"]}
    pd.concat({k: v for k, v in breakdown.items()}, names=["dimension", "group"]).to_csv(
        out.parent / "model_breakdown_test.csv")

    weeks = {"val": (int(val["week_idx"].min()), int(val["week_idx"].max())),
             "test": (int(test["week_idx"].min()), int(test["week_idx"].max()))}
    out.write_text(_build_markdown(metrics, breakdown, models, weeks), encoding="utf-8")
    print(f"Report written: {out}")
    print(metrics[metrics["split"] == "val"].sort_values("mean_pinball")[["model", "mean_pinball"]]
          .to_string(index=False))
    return out


def _split_table(metrics: pd.DataFrame, split: str) -> pd.DataFrame:
    t = (metrics[metrics["split"] == split].set_index("model")
         [["mean_pinball", "cov80", "cov50", "width80", "mae", "rmse", "r2", "wape", "mape_pos"]]
         .sort_values("mean_pinball"))
    base = [b for b in BASELINES if b in t.index]
    if base:
        ref = min(base, key=lambda b: t.loc[b, "mean_pinball"])
        t[f"pinball vs {ref}"] = (t["mean_pinball"] / t.loc[ref, "mean_pinball"] - 1).map(lambda v: f"{v:+.1%}")
    return t.rename(columns={"mean_pinball": "mean pinball", "cov80": "coverage 80%", "cov50": "coverage 50%",
                             "width80": "width 80%", "mape_pos": "MAPE (y>0)", "wape": "WAPE", "mae": "MAE", "rmse": "RMSE", "r2": "R2"})


def _build_markdown(metrics: pd.DataFrame, breakdown: dict, models: list[str], weeks: dict) -> str:
    L = [MARKER, "", "# Model comparison", "",
         "Generated by `python -m src.evaluate_report`. All models are scored by the same code on the same rows "
         f"(validation weeks {weeks['val'][0]}-{weeks['val'][1]}, test weeks {weeks['test'][0]}-{weeks['test'][1]}). **Validation is used to compare and select; "
         "test is reporting only and must not be used to retune or to choose.**", "",
         "How to read: *pinball* lower is better. *coverage* should be close to its target (80% for q10-q90, "
         "50% for q25-q75). *WAPE* is the sum of absolute errors of q50 divided by total demand (safe with zeros); "
         "MAPE is computed on weeks with demand above zero only. *service level* is the share of weeks where "
         "demand was at or below the forecast and should match the quantile level; at low quantiles it cannot "
         "go below the share of zero-demand weeks, so q10 and q25 sit above target.", ""]

    for split, title in [("val", "Validation (model selection)"), ("test", "Test (final reporting)")]:
        L += [f"## {title}", "", _md(_split_table(metrics, split)), ""]

    for split, title in [("val", "Validation"), ("test", "Test")]:
        m = metrics[metrics["split"] == split].set_index("model")
        L += [f"### Pinball loss per quantile ({title.lower()})", "",
              _md(m[[f"pinball_{c}" for c in QUANTILE_COLS]].set_axis(QUANTILE_COLS, axis=1)), "",
              f"### Service level per quantile ({title.lower()})", ""]
        sl = m[[f"sl_{c}" for c in QUANTILE_COLS]].set_axis(QUANTILE_COLS, axis=1)
        sl.loc["target"] = list(QUANTILE_LEVELS.values())
        L += [_md(sl.loc[["target"] + [i for i in sl.index if i != "target"]]), ""]

    L += ["## Test results by group (reporting only)", ""]
    labels = {"dept_id": "Department", "store_id": "Store", "demand_type": "Demand type"}
    for by, tab in breakdown.items():
        pin = tab[["n"] + [f"{m} pinball" for m in models]].rename(columns=lambda c: c.replace(" pinball", ""))
        wap = tab[[f"{m} wape" for m in models]].rename(columns=lambda c: c.replace(" wape", ""))
        L += [f"### {labels[by]}: mean pinball", "", _md(pin, labels[by]), "",
              f"### {labels[by]}: WAPE", "", _md(wap, labels[by]), ""]

    L += _selection_section(metrics)
    L += ["", "## Files", "",
          "- `reports/model_metrics.csv`: every metric for every model and split.",
          "- `reports/model_breakdown_test.csv`: test results by department, store and demand type.", ""]
    return "\n".join(L)


def _selection_section(metrics: pd.DataFrame) -> list[str]:
    val = metrics[(metrics["split"] == "val") & (~metrics["model"].isin(BASELINES))].set_index("model")
    test = metrics[metrics["split"] == "test"].set_index("model")
    ranked = val["mean_pinball"].sort_values()
    best, second = ranked.index[0], (ranked.index[1] if len(ranked) > 1 else None)

    L = ["## Model selection", "",
         "Rule: the candidate (non-baseline) with the lowest **validation** mean pinball is the primary choice.", "",
         f"- Validation winner: **{best}** ({ranked.iloc[0]:.4f}).",
         f"- Test score of that model (check only): {test.loc[best, 'mean_pinball']:.4f}."]
    if second is not None:
        gap = (ranked.iloc[1] - ranked.iloc[0]) / ranked.iloc[0]
        L.append(f"- Runner-up on validation: {second} ({ranked.iloc[1]:.4f}), {gap:.1%} behind.")
        if gap < 0.01:
            L += ["", f"**The gap is under 1%: treat {best} and {second} as tied on validation.** Decide with the "
                      "secondary criteria below (all computed on validation) and write the reason here. "
                      "Do not use the test ranking as the reason."]

    sec = pd.DataFrame({
        "pinball at q75": val["pinball_q75"],
        "coverage 80% gap": (val["cov80"] - 0.80).abs(),
        "coverage 50% gap": (val["cov50"] - 0.50).abs(),
        "WAPE": val["wape"]}).sort_values("pinball at q75")
    L += ["", "Secondary criteria on validation (lower is better in every column; *gap* is the distance from the target coverage):", "", _md(sec, nd=4), "",
          "Decision and reason: _to be written by the team (one paragraph)._"]
    return L


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", type=Path, default=Path("reports/model_comparison.md"))
    p.add_argument("--models", nargs="+", default=None, help="default: every file in predictions/ except fake")
    p.add_argument("--force", action="store_true", help="overwrite an existing report not written by this script")
    a = p.parse_args(argv)
    run(out=a.out, models=a.models, force=a.force)


if __name__ == "__main__":
    main()